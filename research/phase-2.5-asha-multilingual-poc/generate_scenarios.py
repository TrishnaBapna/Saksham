def generate_all_scenarios():
    os.makedirs(SCENARIOS_DIR, exist_ok=True)
    generated = []

    for defn in SCENARIO_DEFINITIONS:
        wav_filename = f"{defn['id']}.wav"
        wav_path = os.path.join(SCENARIOS_DIR, wav_filename)
        
        print(f"Generating [{defn['letter']}] {defn['title']}...")
        
        # Invoke macOS say directly producing 16kHz 16-bit mono PCM WAVE
        cmd_say = [
            "say",
            "-v", defn["voice"],
            "-r", str(defn["rate"]),
            "--file-format=WAVE",
            "--data-format=LEI16@16000",
            "-o", wav_path,
            defn["text"]
        ]
        res = subprocess.run(cmd_say, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"  ❌ Error running say: {res.stderr}")
            continue

        if os.path.exists(wav_path):
            size = os.path.getsize(wav_path)
            # Duration via afinfo
            info_res = subprocess.run(["afinfo", wav_path], capture_output=True, text=True)
            duration = 0.0
            for line in info_res.stdout.splitlines():
                if "estimated duration:" in line:
                    try:
                        duration = float(line.split(":")[1].replace("sec", "").strip())
                    except Exception:
                        pass
            
            rec = dict(defn)
            rec["wav_file"] = wav_filename
            rec["wav_path"] = wav_path
            rec["file_size_bytes"] = size
            rec["duration_seconds"] = round(duration, 3)
            rec["audio_source"] = f"SYNTHETIC TTS (macOS voice: {defn['voice']}, rate: {defn['rate']} WPM)"
            generated.append(rec)
            print(f"  ✓ Created {wav_filename} ({size} bytes, {duration:.2f}s)")
        else:
            print(f"  ❌ File {wav_path} not created.")

    with open(METADATA_FILE, "w", encoding="utf-8") as f:
        json.dump(generated, f, indent=2, ensure_ascii=False)
        
    print(f"\nSuccessfully generated {len(generated)}/10 scenarios in {SCENARIOS_DIR}")
    print(f"Scenario manifest written to {METADATA_FILE}")

if __name__ == "__main__":
    generate_all_scenarios()
