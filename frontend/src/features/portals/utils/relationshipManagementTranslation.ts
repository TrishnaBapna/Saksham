export type RelLangCode = 'en' | 'hi' | 'mr' | 'bn' | 'ta' | 'te' | 'kn';

const normLang = (language?: string): RelLangCode => {
  const short = (language || 'en').toLowerCase().split('-')[0];
  if (
    short === 'hi' ||
    short === 'mr' ||
    short === 'bn' ||
    short === 'ta' ||
    short === 'te' ||
    short === 'kn'
  ) {
    return short;
  }
  return 'en';
};

