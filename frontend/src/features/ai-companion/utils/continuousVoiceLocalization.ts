export function getContinuousVoiceStrings(language?: string): ContinuousVoiceStrings {
  const code = (language || 'en').trim().toLowerCase().split(/[-_]/)[0];
  return CONTINUOUS_VOICE_UI[code] || CONTINUOUS_VOICE_UI.en;
}
