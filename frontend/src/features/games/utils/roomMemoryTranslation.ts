export function translateHomeZone<
  T extends {
    id: string;
    tabLabel: string;
    roomName: string;
    capturedDate: string;
    description: string;
    questions: Array<{
      id: string;
      objectName: string;
      question: string;
      options: string[];
      correctIndex: number;
      clue1: string;
      clue2: string;
      clue3: string;
      revealedAnswer: string;
      connectedRoutine?: { title: string; description: string; estimatedMinutes: number };
    }>;
  },
>(zone: T, language: string): T {
  if (!language || language === 'en') return zone;
  const zTr = EXTRA_ZONES_AND_QUESTIONS[zone.id]?.[language];
  return {
    ...zone,
    tabLabel: zTr?.tabLabel || zone.tabLabel,
    roomName: zTr?.roomName || zone.roomName,
    capturedDate: zTr?.capturedDate || zone.capturedDate,
    description: zTr?.description || zone.description,
    questions: zone.questions.map((q) => {
      const qTr = QUESTION_I18N[q.id]?.[language];
      if (!qTr) return q;
      return {
        ...q,
        objectName: qTr.objectName || q.objectName,
        question: qTr.question || q.question,
        options: qTr.options || q.options,
        clue1: qTr.clue1 || q.clue1,
        clue2: qTr.clue2 || q.clue2,
        clue3: qTr.clue3 || q.clue3,
        revealedAnswer: qTr.revealedAnswer || q.revealedAnswer,
        connectedRoutine: q.connectedRoutine
          ? {
              ...q.connectedRoutine,
              title: qTr.routineTitle || q.connectedRoutine.title,
              description: qTr.routineDesc || q.connectedRoutine.description,
            }
          : undefined,
      };
    }),
  };
}
