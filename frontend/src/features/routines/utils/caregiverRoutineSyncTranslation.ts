export function getRoutineSyncUi(language?: SupportedLanguage | string): RoutineSyncTranslationBundle {
  const short = String(language || 'en').split('-')[0].toLowerCase() as keyof typeof BUNDLES;
  return BUNDLES[short] || BUNDLES.en;
}

export function formatSyncMessage(
  template: string,
  params: Record<string, string | number | undefined>
): string {
  return Object.entries(params).reduce(
    (acc, [key, value]) => acc.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value ?? '')),
    template
  );
}
