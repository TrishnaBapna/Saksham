export type SupportedLang = 'en' | 'hi' | 'mr' | 'bn' | 'ta' | 'te' | 'kn';

const normLang = (lang?: string): SupportedLang => {
  const short = (lang || 'en').toLowerCase().split('-')[0];
  if (
    short === 'hi' ||
    short === 'mr' ||
    short === 'bn' ||
    short === 'ta' ||
    short === 'te' ||
    short === 'kn'
  ) {
    return short;
  }
  return 'en';
};

